    ['Raymer Eq. 15.20 on R_kva, L_a, N_gen vs Brandt''s 0.017*W_TO. R_kva = 80 and L_a = 10 ft ' ...
     'are unpinned estimates, so this row''s agreement is partly a property of those guesses.'], ...
     NaN, 'BY DESIGN')];

T = [T; grow('Hydraulics (Eq. 15.19) [lbf]', 'L3', l3_sys.hydraulics, es.hydraulics.value, 'Brandt Wt!B27', '%.2f', ...
    ['Raymer Eq. 15.19 = 37.23*K_vsh*N_u^0.664 vs Brandt''s 0.0117*W_TO. N_u = 5 is an unpinned ' ...
     'estimate and the equation is very sensitive to it, which is the likely bulk of the gap.'], ...
     NaN, 'BY DESIGN')];

T = [T; grow('ECS / AC + anti-ice (Eq. 15.23) [lbf]', 'L3', l3_sys.ac_antiice, es.ecs_ac_antiice.value, 'Brandt Wt!B28', '%.2f', ...
    ['Raymer Eq. 15.23 on the avionics weight and crew count vs Brandt''s 0.0115*W_TO.'], ...
     NaN, 'BY DESIGN')];

