    ['Raymer Eq. 15.17 on M, S_cs, N_s, N_c vs Brandt''s 0.012*W_TO + a LE-flap area term. ' ...
     'Different families. S_cs = 190 ft^2 is an unpinned geometry estimate, and N_c^0.127 is ' ...
     'FROM-CODE (todo Sec. 3a rows 10-13).'], NaN, 'BY DESIGN')];

