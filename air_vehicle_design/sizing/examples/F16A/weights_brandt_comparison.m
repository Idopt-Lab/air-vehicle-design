    ['A statistical strut-sizing buildup vs Brandt''s 0.034*W_TO fraction -- different formula ' ...
     'families, and they agree to within ~9 %. Was 1057.27 (-0.9 %) before Phase 4, on a FROZEN ' ...
     'W_l = 20681 [Brandt Wt!B41] that made the entire gear group insensitive to gross weight ' ...
     '(todo Sec. P4-17). The apparently better old agreement came from a dead computation.'], ...
     NaN, 'BY DESIGN')];

