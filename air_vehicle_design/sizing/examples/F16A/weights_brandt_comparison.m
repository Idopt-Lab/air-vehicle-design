function T_all = weights_brandt_comparison()
%WEIGHTS_BRANDT_COMPARISON  F-16A Block 10/15 -- Weights vs Brandt ground truth.
%
%   NOT A TEST. No pass/fail assertions, not part of run_all_tests. A pure
%   reporting script: loads the F-16A L1/L2/L3 input JSONs plus
%   examples/F16A/f16a_requirements.json, runs the actual F16WeightsL1/L2/L3
%   methods and the WeightsL2/WeightsL3 static toolboxes, and compares against
%   the `weights` section of VnV/BrandtF16A/GroundTruth/f16a_ground_truth.json
%   -- the Brandt-DIRECT ground truth (NOT F16Baseline.m's older figures, which
%   fidelity_comparison.m uses instead).
%
%   *** INFORMATIONAL ONLY. NEVER PASS/FAIL. AND NOTHING PRODUCED HERE MAY EVER
%   *** BE USED TO BACKFILL A UNIT TEST'S EXPECTED VALUE (CLAUDE.md's two-tier
%   *** rule). The three TestWeights* files' former "OEW = 19,148 lbf [Brandt
%   *** Wt!B12]" assertions are exactly what that rule prevents: Wt!B12 is
%   *** 19,980.70 and 19,148.08 is corrections.xls, a different workbook
%   *** ~4.3 % away (review finding #14). Those assertions were deleted from the
%   *** unit tier in Phase 4 and became the headline rows of this report.
%
%   Where a quantity has multiple valid implementations (Raymer Eq. 10.10
%   uninstalled vs x1.3 vs Brandt's 0.199*T; the L2 psf buildup vs the L3
%   Sec. 15.3.1 buildup), EACH option gets its own row -- never just the
%   official one, and the REJECTED variants are reported too so the decisions
%   stay auditable.
%
%   Outputs (written to the same directory as this script):
%     weights_brandt_comparison.json  -- full table + metadata
%     weights_brandt_comparison.md    -- rendered markdown table
%
%   Specification: examples/F16A/examples/F16A/weights_brandt_comparison.m.
%   Run via `matlab -batch`, not the MCP evaluate tool: the wide-table disp
%   hang is on record.
%
%   REFERENCE SOURCES:
%     [Brandt]  S. Brandt, F-16A.xls workbook, sheet "Wt", via
%               VnV/BrandtF16A/GroundTruth/f16a_ground_truth.json [.weights].
%               Every Wt cell in that block was re-read live over Excel COM on
%               2026-07-25 (todo Sec. P4-0).
%     [Alt]     corrections.xls (Casey's revised-weight workbook), per
%               F16Baseline.m:136 -- a SECOND, DIFFERENT source, never Wt!B12.
%     [Raymer]  D.P. Raymer, Aircraft Design 7th ed., AIAA -- Table 3.1,
%               Table 15.2, Sec. 15.3.1 (Eqs. 15.1-15.24), Eq. 10.10.
%     [Roskam]  J. Roskam, Airplane Design Part I, Eq. 2.16 + Table 2.15.
%     [AE481]   AE481 metabook Sec. 7 "Fraction-Based Weight Estimates".

script_dir  = fileparts(mfilename('fullpath'));
sizing_root = fileparts(fileparts(script_dir));
gt_path     = fullfile(sizing_root, 'VnV', 'BrandtF16A', 'GroundTruth', 'f16a_ground_truth.json');
gt          = jsondecode(fileread(gt_path)).weights;

sc  = gt.structural_components;
es  = gt.engine_and_systems;
sm  = gt.summary;
di  = gt.di_reference_values;

% W_TO basis read from the ground-truth JSON, not hardcoded: Brandt Wt!B3/B38.
W_TO = sm.TOGW.value;   % 31,377 lbf

% The corrections.xls alternate, carried in the Alt column of every row that
% has one. LABELLED, because it is NOT Brandt Wt!B12.
ALT_OEW = sm.OEW.corrections_xls;   % 19,148.08

% ════════════════════════════════════════════════════════════════════════ %
%  BUILD THE FRAMEWORK OBJECTS AND RUN THE ACTUAL DISCIPLINE CODE
% ════════════════════════════════════════════════════════════════════════ %

% Weights takes geometry and propulsion by dependency injection (Phase 4):
% L2 injects F16GeomL2, L3 injects F16GeomL3, and BOTH inject F16PropL2 --
% there is no L3 propulsion tier, so the L3 rung's engine data is an L2 object.
prop = F16PropL2(f16a_spec_path(2));
g2   = F16GeomL2(f16a_spec_path(2), prop);
g3   = F16GeomL3(f16a_spec_path(3), prop);
req  = f16a_requirements_path();

w1 = F16WeightsL1(f16a_spec_path(1));
w2 = F16WeightsL2(f16a_spec_path(2), req, g2, prop);
w3 = F16WeightsL3(f16a_spec_path(3), req, g3, prop);

% ── L1: the two statistical regressions ─────────────────────────────────── %
oew_l1_raymer = w1.OEW(W_TO);                  % Raymer Tbl 3.1 power law
oew_l1_roskam = w1.compute_We_roskam(W_TO);    % Roskam Eq. 2.16 MIN bound

% ── L2: Table 15.2 psf buildup + metabook Sec. 7 fractions ─────────────── %
l2_wing = w2.weight_wing(W_TO);
l2_tail = w2.weight_tail(W_TO);
l2_fus  = w2.weight_fuselage(W_TO);
l2_lg   = w2.weight_landing_gear(W_TO);
l2_ie   = WeightsL2.weight_installed_engine(w2);   % Eq. 10.10 x 1.3 (L2-only)
l2_ale  = WeightsL2.weight_all_else_empty(w2, W_TO);
l2_str  = l2_wing + l2_tail.HT + l2_tail.VT + l2_fus;   % structural subtotal
oew_l2  = w2.OEW(W_TO);

% Engine-weight OPTIONS. Each gets its own row (Sec. G.4 sec. 4).
W_en_uninstalled = w2.W_en;         % Raymer Eq. 10.10, OFFICIAL at L3
W_en_installed   = l2_ie;           % Eq. 10.10 x 1.3, OFFICIAL at L2
W_en_brandt      = w2.W_en_brandt;  % 0.199*T_AB, ALREADY installed
W_en_brandt_x13  = 1.3 * W_en_brandt;                       % REJECTED
oew_l2_brandt_en = oew_l2 - W_en_installed + W_en_brandt;   % alternate
oew_l2_rejected  = oew_l2 - W_en_installed + W_en_brandt_x13; % REJECTED

% ── L3: Raymer Sec. 15.3.1 component buildup ───────────────────────────── %
l3_wing = w3.weight_wing(W_TO);
l3_tail = w3.weight_tail(W_TO);
l3_fus  = w3.weight_fuselage(W_TO);
l3_lg   = w3.weight_landing_gear(W_TO);
l3_eng  = w3.weight_engine_section(W_TO);
l3_sys  = w3.weight_systems(W_TO);
l3_str  = l3_wing + l3_tail.HT + l3_tail.VT + l3_fus;
oew_l3  = w3.OEW(W_TO);
l3_lg_total = l3_lg.main + l3_lg.nose;

w3.W_TO      = W_TO;                 % so the W_TO-dependent Dependents read
l3_W_l       = w3.W_l;               % 0.95 * W_TO (settled decision 4)
l3_sfc       = w3.SFC_mission;       % prop.get_TSFC at the requirements cruise

% The REJECTED L3 "x1.3" variant, reported once so decision 1 stays auditable.
% Reconstructed from the two places W_en enters the engine group: the dry-engine
% line (linear) and Eq. 15.9's W_en^0.717 -- not by editing the class.
sec_uninst = WeightsL3.engine_section(W_en_uninstalled,       w3.N_en, w3.N_z);
sec_x13    = WeightsL3.engine_section(1.3*W_en_uninstalled,   w3.N_en, w3.N_z);
oew_l3_rejected = oew_l3 + 0.3 * W_en_uninstalled * w3.N_en + (sec_x13 - sec_uninst);

% ── Sensitivity variants for the items STILL OPEN after the six decisions ── %
% Each is a fresh object with ONE input changed, so the deltas are independent.
wA = makeL3(req, prop);  wA.L_d = g3.L_duct;        oew_Ld    = wA.OEW(W_TO);
ind_Ld = wA.weight_engine_section(W_TO).induction;
wB = makeL3(req, prop);  wB.D_e = g3.D_exit;        oew_De    = wB.OEW(W_TO);
wC = makeL3(req, prop);  wC.design_mach = 2.05;     oew_M205  = wC.OEW(W_TO);
wD = makeL3(req, prop);  wD.K_d = 0;                oew_Kd0   = wD.OEW(W_TO);
ind_Kd0 = wD.weight_engine_section(W_TO).induction;
ind_base = l3_eng.induction;

% ── The NOT-MODELED gap tally ──────────────────────────────────────────── %
gap_total = sc.nacelles.value + sc.strakes.value ...
          + es.other_structure.value + es.armament_support.value;

% ════════════════════════════════════════════════════════════════════════ %
%  BUILD TABLE
% ════════════════════════════════════════════════════════════════════════ %

SRC_OEW = 'Brandt Wt!B12 (=SUM(B10:B11))';
SRC_EN  = ['Brandt Wt!B11 (=IF(Main!C29=Main!D29,''Engn(s) Old''!D11*Main!B28*Main!C29,' ...
           '''Engn(s) Old''!D22*Main!B28*Main!D29)); 0.199 literal at ''Engn(s)''!D22'];

T = table();

% ─────────────────────────────── SECTION 1 ─────────────────────────────── %
T = [T; srow('[1. OPERATING EMPTY WEIGHT -- THE HEADLINE. Expected = Brandt Wt!B12 = 19,980.70; Alt = corrections.xls 19,148.08]')];

T = [T; grow('OEW, Raymer Tbl 3.1 regression [lbf]', 'L1', oew_l1_raymer, sm.OEW.value, SRC_OEW, '%.2f', ...
    ['Statistical empty-weight power law We/Wto = Kvs*A*W_TO^C, A = 2.34 / C = -0.13 ' ...
     '[metabook_data.md:22]. A CENTRAL regression through historical fighters, so a few ' ...
     'percent is the expected accuracy -- and it happens to land closest to Brandt of ' ...
     'anything in this report.'], ALT_OEW)];

T = [T; grow('OEW, Roskam Eq. 2.16 MINIMUM bound [lbf]', 'L1', oew_l1_roskam, sm.OEW.value, SRC_OEW, '%.2f', ...
    ['DIFFERENT KIND OF QUANTITY: a LOWER BOUND (the historical efficiency frontier), not a ' ...
     'central estimate. Any real OEW must sit ABOVE it, so a negative %Diff is the CORRECT ' ...
     'result and its magnitude is not an error measure. Never summed into OEW.'], ALT_OEW, 'DEFINITIONAL')];

T = [T; grow('OEW, Tbl 15.2 psf buildup + Raymer W_en [lbf]', 'L2', oew_l2, sm.OEW.value, SRC_OEW, '%.2f', ...
    ['OFFICIAL L2. wing 9 / HT 4 / VT 5.3 psf on EXPOSED planform + fuselage 4.8 psf on WETTED ' ...
     'area [Raymer Tbl 15.2] + LG 0.033*W_TO, installed engine 1.3 x bare, all-else 0.17*W_TO ' ...
     '[AE481 metabook Sec. 7]. Of the gap to Brandt, 2733.68 lbf (13.68 % of Wt!B12) is Brandt ' ...
     'components with NO framework analog -- see section 5.'], ALT_OEW)];

T = [T; grow('OEW, Tbl 15.2 psf buildup + Brandt W_en alt [lbf]', 'L2', oew_l2_brandt_en, sm.OEW.value, SRC_OEW, '%.2f', ...
    ['Same buildup with Brandt''s own already-installed 0.199*T_AB engine weight substituted ' ...
     '(NO x1.3). A different engine-model FAMILY, so the framework is expected to differ; ' ...
     'reported because engine weight is the single largest divergence at L2.'], ALT_OEW, 'BY DESIGN')];

T = [T; grow('OEW, Tbl 15.2 psf + Brandt W_en x1.3 -- REJECTED [lbf]', '--', oew_l2_rejected, sm.OEW.value, SRC_OEW, '%.2f', ...
    ['REJECTED VARIANT, reported so the decision is auditable. Applies the metabook''s x1.3 to a ' ...
     'formula readme_wt.md:230 states IS ALREADY the installed-engine weight, i.e. it installs ' ...
     'twice. It agrees BEST with Brandt of every L2 option, and that is precisely why it is ' ...
     'rejected: agreement produced by a double-counted factor is not agreement. Not a candidate.'], ...
     ALT_OEW, 'DEFINITIONAL')];

T = [T; grow('OEW, Raymer Sec. 15.3.1 buildup [lbf]', 'L3', oew_l3, sm.OEW.value, SRC_OEW, '%.2f', ...
    ['OFFICIAL L3, at the settled decisions: UNINSTALLED W_en (no x1.3), W_l = 0.95*W_TO, ' ...
     'SFC_mission by DI at the requirements cruise point. Eqs. 15.1-15.24 group mass differently ' ...
     'from Brandt''s psf model, and the same 2733.68 lbf of unmodelled Brandt components applies.'], ...
     ALT_OEW)];

T = [T; grow('OEW, Sec. 15.3.1 with W_en x1.3 -- REJECTED [lbf]', '--', oew_l3_rejected, sm.OEW.value, SRC_OEW, '%.2f', ...
    ['REJECTED VARIANT, reported so decision 1 is auditable. It is CLOSER to Brandt than the ' ...
     'settled answer, because it double-counts the installation hardware Eqs. 15.7-15.15 already ' ...
     'supply item by item. The better agreement was the evidence AGAINST x1.3, not for it. ' ...
     'x1.3 is L2-only, and L2 has no buildup.'], ALT_OEW, 'DEFINITIONAL')];

% ─────────────────────────────── SECTION 2 ─────────────────────────────── %
T = [T; srow('[2. STRUCTURAL LINE ITEMS -- Brandt Wt!C9:H9. His psf coefficients are Wt!C7:H7 (wing 6.75 / fus 5.0 / pitch 6.0 / VT 6.0), NOT Raymer Tbl 15.2''s]')];

T = [T; grow('Wing [Tbl 15.2 psf] [lbf]', 'L2', l2_wing, sc.wing.value, 'Brandt Wt!C9', '%.2f', ...
    ['Framework: 9.0 psf x EXPOSED planform 196.2261 ft^2 [Raymer Tbl 15.2, metabook_data.md:321]. ' ...
     'Brandt: 6.75 psf x S_ref with AR^1.8, n_ult^0.2, tc^-0.7 and 1/cos(Lambda) factors -- a ' ...
     'psf model like ours but a different coefficient AND different correction factors.'], ...
     sc.wing.corrections_xls)];

T = [T; grow('Wing [Eq. 15.1] [lbf]', 'L3', l3_wing, sc.wing.value, 'Brandt Wt!C9', '%.2f', ...
    ['Raymer Eq. 15.1 statistical buildup. Reads ~34 % above Brandt: Raymer''s fighter-wing ' ...
     'regression is fitted across production aircraft and does not capture the F-16''s unusually ' ...
     'light, highly optimised wing. Raymer states these are estimates with intrinsic scatter. ' ...
     'Every Eq. 15.1 exponent is an OPEN verify-against-book item (todo Sec. 3a).'], ...
     sc.wing.corrections_xls)];

T = [T; grow('Fuselage [Tbl 15.2 psf] [lbf]', 'L2', l2_fus, sc.fuselage.value, 'Brandt Wt!D9', '%.2f', ...
    ['Framework: 4.8 psf x WETTED area 730.3023 ft^2 [Raymer Tbl 15.2, metabook_data.md:324; area ' ...
     'via Roskam Vol. II Eq. 12.3]. Brandt: 5.0 psf x his own S_wet_fuse 730.422 x a fineness ' ...
     'factor -- nearly the same area, so this row isolates the psf coefficient difference.'], ...
     sc.fuselage.corrections_xls)];

T = [T; grow('Fuselage [Eq. 15.4] [lbf]', 'L3', l3_fus, sc.fuselage.value, 'Brandt Wt!D9', '%.2f', ...
    ['Raymer Eq. 15.4, on the 47.5 ft T.O. length and the 5.0 ft maximum structural DEPTH. ' ...
     '! D_fus here is NOT geom.D_fus = 6.0 (the Roskam equivalent diameter): Eq. 15.4 carries ' ...
     'D_fus^0.849, so that substitution would inflate this row by +17.9 % silently.'], ...
     sc.fuselage.corrections_xls)];

T = [T; grow('Pitch control / HT [Tbl 15.2 psf] [lbf]', 'L2', l2_tail.HT, sc.pitch_control_HT.value, 'Brandt Wt!E9', '%.2f', ...
    ['DIFFERENT AREA CONVENTION, not an agreement check. Brandt Wt!E9 = 6.0 x Main!C18 = 6.0 x 108, ' ...
     'the FULL planform; the framework uses the EXPOSED planform per Raymer Tbl 15.2''s own ' ...
     'definition (49.8473 ft^2 at L2). The Alt column''s 199.39 is close only because ' ...
     'corrections.xls happens to land near 4.0 x exposed.'], ...
     sc.pitch_control_HT.corrections_xls, 'DEFINITIONAL')];

T = [T; grow('Pitch control / HT [Eq. 15.2] [lbf]', 'L3', l3_tail.HT, sc.pitch_control_HT.value, 'Brandt Wt!E9', '%.2f', ...
    ['Same FULL-vs-EXPOSED definitional split as the L2 row. Raymer Eq. 15.2 on the EXPOSED ' ...
     '51.1486 ft^2, which is +2.605 % above L2''s 49.8473 because F16GeomL3 takes the physical ' ...
     '18.5 ft HT span as primary (F16GeomL3.md §4) -- itself BY DESIGN, not error.'], ...
     sc.pitch_control_HT.corrections_xls, 'DEFINITIONAL')];

T = [T; grow('Vertical tail [Tbl 15.2 psf] [lbf]', 'L2', l2_tail.VT, sc.vertical_tail.value, 'Brandt Wt!F9', '%.2f', ...
    ['DIFFERENT AREA CONVENTION. Brandt Wt!F9 = 6.0 x Main!H18 = 6.0 x 60, the FULL planform; ' ...
     'the framework uses the EXPOSED 40.8897 ft^2 x 5.3 psf [metabook_data.md:323].'], ...
     sc.vertical_tail.corrections_xls, 'DEFINITIONAL')];

T = [T; grow('Vertical tail [Eq. 15.3] [lbf]', 'L3', l3_tail.VT, sc.vertical_tail.value, 'Brandt Wt!F9', '%.2f', ...
    ['Same FULL-vs-EXPOSED split. Raymer Eq. 15.3 on the EXPOSED planform SET -- S_vt 40.8897, ' ...
     'AR_vt 1.294, lambda_vt 0.437 -- NOT the FULL 60 / 1.6 / 0.5. Eq. 15.3 also carries a ' ...
     'documented code-vs-extract exponent CONFLICT on cos(Lambda_vt) (todo Sec. 3a row 2).'], ...
     sc.vertical_tail.corrections_xls, 'DEFINITIONAL')];

T = [T; grow('Nacelles -- NOT MODELED [lbf]', 'N/A', NaN, sc.nacelles.value, 'Brandt Wt!G9', '%.2f', ...
    ['No framework nacelle-weight component exists at any fidelity level. Brandt: 4.5 psf x his ' ...
     'half-buried nacelle area (Geom!B4). Counted in the section-5 gap tally.'], ...
     sc.nacelles.corrections_xls, 'DEFINITIONAL')];

T = [T; grow('Strakes -- NOT MODELED [lbf]', 'N/A', NaN, sc.strakes.value, 'Brandt Wt!H9', '%.2f', ...
    ['No framework strake component exists -- the same gap the geometry report records for strake ' ...
     'wetted/exposed area. Brandt: 4.5 psf x 20 ft^2. Counted in the section-5 gap tally.'], ...
     sc.strakes.corrections_xls, 'DEFINITIONAL')];

T = [T; grow('Structural subtotal, Tbl 15.2 (wing+fus+HT+VT) [lbf]', 'L2', l2_str, sc.structural_subtotal.value, 'Brandt Wt!B9', '%.2f', ...
    ['NOT LIKE-FOR-LIKE: Brandt''s Wt!B9 = SUM(C9:H9) also contains nacelles (186.82) and strakes ' ...
     '(90.00), for which the framework has no analog, and two of the four shared items use his ' ...
     'FULL-planform tail areas. Group-level agreement is not meaningful here.'], NaN, 'DEFINITIONAL')];

T = [T; grow('Structural subtotal, Eqs. 15.1-15.4 (wing+fus+HT+VT) [lbf]', 'L3', l3_str, sc.structural_subtotal.value, 'Brandt Wt!B9', '%.2f', ...
    'Same non-like-for-like subtotal as the L2 row, over the Sec. 15.3.1 components.', ...
    NaN, 'DEFINITIONAL')];

% ─────────────────────────────── SECTION 3 ─────────────────────────────── %
T = [T; srow('[3. ENGINE + SYSTEMS -- Brandt Wt!B22:B31. His fraction literals are Wt!F23:F31, live-verified 2026-07-25]')];

T = [T; grow('Landing gear, total [lbf]', 'L2', l2_lg, es.landing_gear.value, 'Brandt Wt!B23 (=B8 = B3*F23)', '%.2f', ...
    ['SAME MODEL FAMILY, different coefficient: framework 0.033*W_TO [AE481 metabook Sec. 7, ' ...
     'metabook_data.md:330] vs Brandt 0.034*W_TO (Wt!F23 = 0.034, a bare literal). LOCKED decision ' ...
     '(user 2026-07-24): use 0.033. The -2.94 % is exactly 0.033/0.034 - 1, i.e. entirely the ' ...
     'coefficient choice.'], NaN, 'BY DESIGN')];

T = [T; grow('Landing gear, main only (Eq. 15.5) [lbf]', 'L3', l3_lg.main, NaN, 'no single Brandt cell', '%.2f', ...
    ['Brandt carries ONE gear line; the framework splits main (Eq. 15.5) and nose (Eq. 15.6), so ' ...
     'only the total below compares. Reported for the breakdown. L_m is converted feet->INCHES ' ...
     'per Raymer''s nomenclature; omitting that made the gear ~11x too light.'], NaN, 'DEFINITIONAL')];

T = [T; grow('Landing gear, nose only (Eq. 15.6) [lbf]', 'L3', l3_lg.nose, NaN, 'no single Brandt cell', '%.2f', ...
    'See the main-gear row: Brandt has no nose/main split.', NaN, 'DEFINITIONAL')];

